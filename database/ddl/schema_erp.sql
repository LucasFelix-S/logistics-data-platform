CREATE SCHEMA IF NOT EXISTS erp;

CREATE TABLE erp.produtos (
    codigo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(255) NOT NULL,
    unidade_medida CHAR(2) NOT NULL,
    estoque_minimo INTEGER,
    estoque_maximo INTEGER,
    categoria_id INTEGER NOT NULL,
    status_id INTEGER NOT NULL
);
CREATE TABLE erp.categorias (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(255) NOT NULL
);
CREATE TABLE erp.status (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(255) NOT NULL
);
CREATE TABLE erp.condicoes_pagamento (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(255) NOT NULL
);
CREATE TABLE erp.parcelas_condicoes_pagamento (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    condicao_pagamento_id INTEGER NOT NULL,
    numero_parcela INTEGER NOT NULL,
    prazo_dias INTEGER NOT NULL,
    percentual NUMERIC(5,2) NOT NULL
);
CREATE TABLE erp.entidades (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    tipo_entidade_id INTEGER NOT NULL
);
CREATE TABLE erp.tipos_entidades (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(255) NOT NULL
);
CREATE TABLE erp.pedidos_venda (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id INTEGER NOT NULL,
    data_pedido TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    status_id INTEGER NOT NULL,
    condicao_pagamento_id INTEGER NOT NULL,
    valor_total NUMERIC(10,2) NOT NULL
);
CREATE TABLE erp.itens_pedidos_venda (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id INTEGER NOT NULL,
    produto_id INTEGER NOT NULL,
    quantidade INTEGER NOT NULL,
    preco_unitario NUMERIC(10,2) NOT NULL,
    desconto NUMERIC(5,2)
);
CREATE TABLE erp.status_pedidos_venda (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(255) NOT NULL
);
CREATE TABLE erp.tabelas_preco (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    vigencia_inicio TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    vigencia_fim TIMESTAMP WITHOUT TIME ZONE,
    status_id INTEGER NOT NULL
);
CREATE TABLE erp.status_tabelas_preco (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(255) NOT NULL
);
CREATE TABLE erp.itens_tabelas_preco (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tabela_id INTEGER NOT NULL,
    produto_id INTEGER NOT NULL,
    preco NUMERIC(10,2) NOT NULL
);
CREATE TABLE erp.pedidos_compra (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fornecedor_id INTEGER NOT NULL,
    data_pedido TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    status_id INTEGER NOT NULL,
    previsao_entrega TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
CREATE TABLE erp.itens_pedidos_compra (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id INTEGER NOT NULL,
    produto_id INTEGER NOT NULL,
    quantidade INTEGER NOT NULL,
    custo_unitario NUMERIC(10,2) NOT NULL
);
CREATE TABLE erp.status_pedidos_compra (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(255) NOT NULL
);
CREATE TABLE erp.contas_receber (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_venda_id INTEGER NOT NULL,
    valor NUMERIC(10,2) NOT NULL
);
CREATE TABLE erp.contas_pagar (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_compra_id INTEGER NOT NULL,
    valor NUMERIC(10,2) NOT NULL
);
CREATE TABLE erp.parcelas_receber (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_parcela INTEGER NOT NULL,
    conta_receber_id INTEGER NOT NULL,
    valor NUMERIC(10,2) NOT NULL,
    vencimento TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    pagamento TIMESTAMP WITHOUT TIME ZONE
);
CREATE TABLE erp.parcelas_pagar (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_parcela INTEGER NOT NULL,
    conta_pagar_id INTEGER NOT NULL,
    valor NUMERIC(10,2) NOT NULL,
    vencimento TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    pagamento TIMESTAMP WITHOUT TIME ZONE
);

